-- Crear tabla para datos históricos de faltas (años anteriores sin detalle individual)
-- Esta tabla almacena SOLO agregados por caso-mes-año
-- Permite comparativas sin falsificar registros individuales

CREATE TABLE IF NOT EXISTS faltas_historico (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    id_caso INTEGER NOT NULL,
    año INTEGER NOT NULL,
    mes INTEGER NOT NULL,
    cantidad INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY(id_caso) REFERENCES casos(id),
    UNIQUE(id_caso, año, mes)
);

